// The UX loop's adapter for the Spindle documentation site (SKILL.md § 1, docs-site values): the
// slots the generic core in `ux/core/` reads.

import { existsSync, readFileSync } from 'node:fs';
import { join } from 'node:path';
import type { Adapter, Card, Required, SitePage, Task, Viewport } from './core/types.ts';

const here = import.meta.dirname;
const site = join(here, '..');
export const port = Number(process.env.UX_PORT ?? 4320);
export const origin = `http://127.0.0.1:${port}`;
const basePath = '/spindle/';

/** Docusaurus shows the desktop navbar and the docs sidebar above 996 px. */
const DESKTOP = 997;

/** The built site the loop reads: `website/build`, or `UX_BUILD`. */
export const build = process.env.UX_BUILD ?? join(site, 'build');

/** The pages of the built sitemap, each named by its path; generated pages carry `custom_edit_url: null`. */
export function sitemapPages(): SitePage[] {
  const file = join(build, 'sitemap.xml');
  if (!existsSync(file)) throw new Error(`no ${file}: build the site first (npm --prefix website run build)`);
  const locs = [...readFileSync(file, 'utf8').matchAll(/<loc>([^<]+)<\/loc>/g)].map((m) => new URL(m[1]!).pathname);
  return locs
    .map((p) => p.slice(basePath.length).replace(/\/$/, ''))
    .sort()
    .map((path) => {
      const source = path === '' ? null : path === 'docs' ? 'docs/index.md' : `${path}.md`;
      const text = source && existsSync(join(site, source)) ? readFileSync(join(site, source), 'utf8') : '';
      return { name: path === '' ? 'landing' : path.replace(/^docs\/?/, '').replace(/\//g, '-') || 'docs', path, generated: /custom_edit_url: null|generated by/.test(text) };
    });
}

const json = <T>(file: string): T => JSON.parse(readFileSync(join(here, 'scenarios', file), 'utf8')) as T;

export const adapter: Adapter = {
  name: 'Spindle documentation site (website/, Docusaurus)',
  base: `${origin}${basePath}`,
  gating: [
    { name: '1280x800', width: 1280, height: 800 },
    { name: '390x844', width: 390, height: 844 },
  ],
  measured: [
    { name: '1440x900', width: 1440, height: 900 },
    { name: '1024x768', width: 1024, height: 768 },
    { name: '768x1024', width: 768, height: 1024 },
  ],
  themes: [
    { name: 'light', colorScheme: 'light' },
    { name: 'dark', colorScheme: 'dark' },
  ],
  get pages() {
    return sitemapPages();
  },
  tasks: json<{ tasks: Task[] }>('tasks.json').tasks,
  cards: json<{ cards: Card[] }>('cards.json').cards,
  alwaysVisible(viewport: Viewport): Required[] {
    const common: Required[] = [
      { name: 'navbar', selector: 'nav.navbar' },
      { name: 'search', selector: 'nav.navbar :is(input[type="search"], .DocSearch-Button, [class*="searchBox"] input, [aria-label="Search" i])' },
      { name: 'theme toggle', selector: 'nav.navbar [class*="colorModeToggle"] button' },
    ];
    return viewport.width >= DESKTOP
      ? [...common, { name: 'docs sidebar', selector: 'nav[aria-label="Docs sidebar"]', onlyWhere: '.theme-doc-sidebar-container' }]
      : [...common, { name: 'navigation menu button', selector: 'nav.navbar button.navbar__toggle' }];
  },
  navigation: ['nav.navbar', 'nav[aria-label="Docs sidebar"]', '.table-of-contents', '.navbar-sidebar'],
  article: 'article .markdown',
  reveal: [
    { role: 'button', name: 'Toggle navigation bar' },
    { role: 'button', name: 'On this page' },
  ],
  dismiss: [{ role: 'button', name: 'Close navigation bar' }],
  explore: [{ role: 'link', name: 'Documentation' }],
  notReady: '[class*="toggleButtonDisabled"]',
  search: { role: 'searchbox', name: 'Search' },
};
